import type { AmenityId, Station, StationTier } from '@/types/rail';

type StationSeed = {
  id: string;
  code: string;
  nameAr: string;
  nameEn: string;
  governorateAr: string;
  governorateEn: string;
  lat: number;
  lng: number;
  tier: StationTier;
  lineIds: string[];
  aliasesAr?: string[];
  aliasesEn?: string[];
  amenities?: AmenityId[];
  descriptionAr?: string;
  descriptionEn?: string;
};

const tierAmenities: Record<StationTier, AmenityId[]> = {
  1: ['tickets', 'machine', 'waiting', 'cafe', 'taxi', 'atm', 'accessible', 'parking'],
  2: ['tickets', 'machine', 'waiting', 'cafe', 'taxi', 'accessible'],
  3: ['tickets', 'waiting', 'taxi'],
  4: ['waiting'],
};

function station(seed: StationSeed): Station {
  const amenities = seed.amenities ?? [...tierAmenities[seed.tier]];
  return {
    ...seed,
    aliasesAr: seed.aliasesAr ?? [],
    aliasesEn: seed.aliasesEn ?? [],
    amenities,
    searchable: seed.tier < 4,
    status: 'active',
    descriptionAr:
      seed.descriptionAr ??
      `محطة ${seed.nameAr} في محافظة ${seed.governorateAr}. تظهر هنا مواعيد الرحلات ولوحة الحركة المباشرة، مع تفاصيل الخطوط والمرافق المتاحة داخل المحطة.`,
    descriptionEn:
      seed.descriptionEn ??
      `${seed.nameEn} station in ${seed.governorateEn}. Browse live departures, arrivals, lines and station facilities.`,
  };
}

