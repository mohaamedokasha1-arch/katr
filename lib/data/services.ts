function reversePattern(points: PatternPoint[]): PatternPoint[] {
  const n = points.length;
  return points.map((point, index) => {
    if (index === 0) {
      return {
        stationId: points[n - 1].stationId,
        travelFromPrev: 0,
        wait: 0,
        distanceFromPrev: 0,
      };
    }
    const original = points[n - index];
    const originalStation = points[n - 1 - index];
    return {
      stationId: originalStation.stationId,
      travelFromPrev: original.travelFromPrev,
      wait: originalStation.wait,
      distanceFromPrev: original.distanceFromPrev,
    };
  });
}

function buildStops(points: PatternPoint[], pace: number): ServiceStop[] {
  let previousDeparture = 0;
  let cumulativeDistance = 0;
  return points.map((point, index) => {
    cumulativeDistance += point.distanceFromPrev;
    if (index === 0) {
      return {
        stationId: point.stationId,
        arrivalOffset: null,
        departureOffset: 0,
        distanceKm: 0,
      };
    }
    const travel = Math.max(1, Math.round(point.travelFromPrev * pace));
    const arrival = previousDeparture + travel;
    const departure = arrival + point.wait;
    previousDeparture = departure;
    return {
      stationId: point.stationId,
      arrivalOffset: arrival,
      departureOffset: departure,
      distanceKm: cumulativeDistance,
    };
  });
}

type FareSeed = Partial<Record<TrainClassId, [number, number]>>;

interface ServiceSeed {
  number: string;
  lineId: string;
  patternId: string;
  departureMinutes: number;
  direction?: 'outbound' | 'inbound';
  pace?: number;
  classes: TrainClassId[];
  fares: FareSeed;
  operatingDays?: OperatingDays;
  season?: Service['season'];
  features?: ServiceFeature[];
  lastVerifiedDaysAgo?: number;
  popularity?: number;
  titleAr?: string;
  titleEn?: string;
  notesAr?: string;
  notesEn?: string;
}

function defineService(seed: ServiceSeed): Service {
  const direction = seed.direction ?? 'outbound';
  const pattern = SERVICE_PATTERNS[seed.patternId];
  if (!pattern) throw new Error(`Unknown pattern ${seed.patternId} for ${seed.number}`);
  const points = direction === 'inbound' ? reversePattern(pattern) : pattern;
  const stops = buildStops(points, seed.pace ?? 1);

  const fares: FareRange[] = seed.classes.map((classId) => {
    const range = seed.fares[classId];
    if (!range) throw new Error(`Missing fare for ${seed.number} / ${classId}`);
    return { classId, min: range[0], max: range[1] };
  });

  return {
    number: seed.number,
    lineId: seed.lineId,
    titleAr: seed.titleAr,
    titleEn: seed.titleEn,
    departureMinutes: seed.departureMinutes,
    direction,
    patternId: seed.patternId,
    stops,
    classes: seed.classes,
    fares,
    operatingDays: seed.operatingDays ?? { type: 'daily' },
    season: seed.season,
    features: seed.features ?? ['luggage'],
    lastVerifiedDaysAgo: seed.lastVerifiedDaysAgo ?? 3,
    popularity: seed.popularity ?? 50,
    notesAr: seed.notesAr,
    notesEn: seed.notesEn,
  };
}

